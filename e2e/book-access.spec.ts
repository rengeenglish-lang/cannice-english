import { expect, test } from "@playwright/test";
import { readFileSync } from "node:fs";
const baseURL = process.env.NETFENER_E2E_BASE_URL ?? "http://localhost:3000";
test.use({ baseURL, channel: process.env.NETFENER_E2E_CHANNEL, ignoreHTTPSErrors: true });

test("book registration, email confirmation, first PDF, review unlock and print disclosure", async ({ page, request }, testInfo) => {
  test.skip(process.env.CI !== "true", "Uses the isolated CI email recorder");
  test.setTimeout(90000);
  await page.goto("/kaynaklar/e-kitaplar/onizleme/yokdil-saglik");
  await expect(page.getByText("PDF için ücretsiz hesap gerekir.", { exact: false })).toHaveCount(0);
  await page.getByRole("button", { name: "Tümünü reddet", exact: true }).click();
  await page.getByRole("link", { name: "Ücretsiz al", exact: true }).first().click();
  await expect(page).toHaveURL(/\/register\?next=/);
  const email = `book-browser-${Date.now()}@example.test`;
  await page.getByLabel("Adın Soyadın", { exact: true }).fill("Kitap Test Kullanıcısı");
  await page.getByLabel("E-posta", { exact: true }).fill(email);
  await page.getByLabel("Şifre", { exact: true }).fill("TestPassword-2026!");
  await page.locator('input[name="terms"]').check();
  await page.getByRole("button", { name: "Kitabım için kaydol", exact: true }).click();
  await expect(page).toHaveURL(/\/kitap-kaydini-tamamla\?book=yokdil-saglik/);
  await expect(page.getByText("e-posta gönderilemedi", { exact: false })).toHaveCount(0);
  const messages = readFileSync("/tmp/netfener-test-mail.jsonl", "utf8").trim().split("\n").map(line => JSON.parse(line));
  const mail = messages.find(message => message.to.includes(email));
  expect(mail).toBeTruthy();
  const verification = mail.text.match(/https:\/\/[^\s]+\/kitap-dogrulama\?t=[\w-]{43}/)[0];
  // A mail scanner may fetch the page; GET must not burn the login link.
  expect((await request.get(verification)).status()).toBe(200);
  await page.goto(verification);
  await expect(page).toHaveURL(/\/dashboard\/books$/);
  const first = page.getByRole("article", { name: "YÖKDİL Sağlık", exact: true });
  await expect(first).toBeVisible();
  await expect(first.getByRole("link", { name: "Online oku", exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("book-library-before-download.png"), fullPage: true });
  const claimResponse = page.waitForResponse(response => response.request().method() === "POST" && new URL(response.url()).pathname === "/api/ebooks/yokdil-saglik");
  const download = page.waitForEvent("download", { timeout: 15000 });
  await first.getByRole("button", { name: "PDF indir", exact: true }).click();
  const claim = await claimResponse;
  expect(claim.status(), await claim.text()).toBe(200);
  expect((await download).suggestedFilename()).toBe("netfener-yokdil-saglik.pdf");
  await page.goto("/dashboard/books?book=yokdil-fen");
  const second = page.getByRole("article", { name: "YÖKDİL Fen Bilimleri", exact: true });
  await expect(second.getByText("İkinci ve sonraki PDF", { exact: false })).toBeVisible();
  await expect(second.getByRole("button", { name: "PDF indir", exact: true })).toHaveCount(0);
  const blocked = await page.request.post("/api/ebooks/yokdil-fen", { headers: { origin: baseURL } });
  expect(blocked.status()).toBe(403);
  expect((await blocked.json()).code).toBe("REVIEW_REQUIRED");
  await second.getByRole("link", { name: "Yorumumu paylaş ve tüm kitapları aç", exact: true }).click();
  await page.getByRole("button", { name: "1 yıldız", exact: true }).click();
  await page.locator('textarea[name="body"]').fill("İlk kitabı ve örnek sayfaları inceledim. Anlatımı yararlı buldum, bazı bölümlerde daha fazla çözümlü örnek görmek isterim.");
  await page.getByRole("button", { name: "Yorumu gönder", exact: true }).click();
  await expect(page.getByRole("link", { name: "Tüm kitaplarımı aç", exact: true })).toBeVisible();
  await page.getByRole("link", { name: "Tüm kitaplarımı aç", exact: true }).click();
  await expect(page.getByRole("article")).toHaveCount(11);
  await page.screenshot({ path: testInfo.outputPath("book-library-after-review.png"), fullPage: true });
  const secondUnlocked = page.getByRole("article", { name: "YÖKDİL Fen Bilimleri", exact: true });
  const nextDownload = page.waitForEvent("download");
  await secondUnlocked.getByRole("button", { name: "PDF indir", exact: true }).click();
  expect((await nextDownload).suggestedFilename()).toBe("netfener-yokdil-fen.pdf");
  await first.getByRole("button", { name: "Basılı kitap iste", exact: true }).click();
  const modal = page.getByRole("dialog", { name: "YÖKDİL Sağlık: basılı kitap" });
  await expect(modal.getByText("Ücretsiz indirmelere basılı kitap dahil değildir.", { exact: false })).toBeVisible();
  await modal.getByRole("button", { name: "Ücretli basılı kitap almak istiyorum", exact: true }).click();
  await expect(modal.getByText("2 hafta içinde adresine teslim edilir.", { exact: false })).toBeVisible();
  await expect(modal.getByRole("button", { name: "Hızlı Ekle", exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("print-delivery-notice.png") });
  await page.keyboard.press("Escape");
  // Successful login consumed the token, so another browser cannot replay it.
  const fresh = await page.context().browser()!.newContext({ ignoreHTTPSErrors: true });
  const replay = await fresh.newPage();
  await replay.goto(verification);
  await expect(replay.getByText("Bağlantının süresi dolmuş veya daha önce kullanılmış.", { exact: false })).toBeVisible();
  await fresh.close();
});
